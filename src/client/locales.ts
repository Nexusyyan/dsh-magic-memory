export type TranslateFn = (key: MagicMemoryLocaleKey, params?: Record<string, unknown>) => string

export function interpolate(template: string, params?: Record<string, unknown>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    params[k] !== undefined ? String(params[k]) : `{${k}}`,
  )
}

export function createFallbackTranslator(lang: 'en' | 'zh' = 'en'): TranslateFn {
  const dict = lang === 'zh' ? ZH_DICT : EN_DICT
  return (key, params) => interpolate(dict[key] ?? EN_DICT[key] ?? key, params)
}
