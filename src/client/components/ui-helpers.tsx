import React from 'react'
import type { MemoryCategory } from '../../shared/types.js'
import type { MagicMemoryLocaleKey, TranslateFn } from '../locales.js'

export const CATEGORY_COLORS: Record<MemoryCategory, string> = {
  PROJECT_RULES: '#4176e6',
  ARCHITECTURE: '#8b5cf6',
  CONSTRAINTS: '#f59e0b',
  CONFIG_VALUES: '#14b8a6',
  NAMING: '#ec4899',
  USER_PROFILE: '#22c55e',
}

export function getCategoryLabel(t: TranslateFn, category: MemoryCategory): string {
  return t(`cat.${category}` as MagicMemoryLocaleKey)
}

export function getVerificationLabel(t: TranslateFn, state: string): string {
  if (state === 'verified') return t('verify.verified')
  if (state === 'stale') return t('verify.stale')
  if (state === 'conflict') return t('verify.conflict')
  if (state === 'unverified') return t('verify.unverified')
  return state
}

export function getSourceKindLabel(t: TranslateFn, sourceKind: string): string {
  if (sourceKind === 'manual') return t('source.manual')
  if (sourceKind === 'auto_extracted') return t('source.auto_extracted')
  if (sourceKind === 'dreamer_promoted') return t('source.dreamer_promoted')
  if (sourceKind === 'tool') return t('source.tool')
  if (sourceKind === 'imported') return t('source.imported')
  return sourceKind
}

export function CategoryDot({ category }: { category: MemoryCategory }): React.ReactElement {
  return (
    <span
      className="dmm-dot"
      style={{ backgroundColor: CATEGORY_COLORS[category] ?? '#6b7280' }}
      aria-hidden="true"
    />
  )
}

